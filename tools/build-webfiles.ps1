<#
  Regenerates src\TafnitCore.System.UI.App.Tools.Helper.WebFiles.cls from the files in web\.
  Run after every change to web\xtafnit-rh.js or web\helper.html, then commit both.
  The files are embedded as base64 so the bytes (including the UTF-8 BOM of helper.html) are kept exactly.
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$files = [ordered]@{
    'XtafnitRhJs' = @{ Source = 'web\xtafnit-rh.js'; Target = 'scripts\xtafnit-rh.js' }
    'HelperHtml'  = @{ Source = 'web\helper.html';   Target = 'helper.html' }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/// Generated by tools\build-webfiles.ps1 - do not edit by hand.')
[void]$sb.AppendLine('/// The web files of the remote-help solution, embedded as base64 (exact bytes).')
[void]$sb.AppendLine('/// Deploy(path) writes them under the CSP folder of /xtafnit (called by install^core.TafnitHelperUtils).')
[void]$sb.AppendLine('Class TafnitCore.System.UI.App.Tools.Helper.WebFiles [ Abstract ]')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/// Writes every embedded file under pPath (the CSP folder). pLog(n) = one line per file.')
[void]$sb.AppendLine('ClassMethod Deploy(pPath As %String, Output pLog) As %Status')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    set tSC=$$$OK, pLog=0, pPath=##class(%File).NormalizeDirectory(pPath)')
[void]$sb.AppendLine('    for tName=' + (($files.Keys | ForEach-Object { '"' + $_ + '"' }) -join ',') + ' {')
[void]$sb.AppendLine('        set tXData=##class(%Dictionary.CompiledXData).%OpenId(..%ClassName(1)_"||"_tName)')
[void]$sb.AppendLine('        if ''$ISOBJECT(tXData) { set tSC=$$$ERROR($$$GeneralError,"XData "_tName_" missing") quit }')
[void]$sb.AppendLine('        set tText="" do tXData.Data.Rewind()')
[void]$sb.AppendLine('        while ''tXData.Data.AtEnd { set tText=tText_tXData.Data.Read(32000) }')
[void]$sb.AppendLine('        set tTarget=$PIECE($PIECE(tText,"target=""",2),"""",1)')
[void]$sb.AppendLine('        set tB64=$TRANSLATE($PIECE($PIECE(tText,">",2),"<",1),$CHAR(9,10,13,32))')
[void]$sb.AppendLine('        set tFile=pPath_tTarget')
[void]$sb.AppendLine('        do ##class(%File).CreateDirectoryChain(##class(%File).GetDirectory(tFile))')
[void]$sb.AppendLine('        set tOut=##class(%Stream.FileBinary).%New()')
[void]$sb.AppendLine('        set tSC=tOut.LinkToFile(tFile) quit:$$$ISERR(tSC)')
[void]$sb.AppendLine('        do tOut.Write($SYSTEM.Encryption.Base64Decode(tB64))')
[void]$sb.AppendLine('        set tSC=tOut.%Save() quit:$$$ISERR(tSC)')
[void]$sb.AppendLine('        set pLog=pLog+1, pLog(pLog)=tFile')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('    quit tSC')
[void]$sb.AppendLine('}')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/// Writes and compiles the routine core.TafnitHelperUtils from XData RoutineMac.')
[void]$sb.AppendLine('/// Used by Install when $SYSTEM.OBJ.LoadDir did not load the .mac file (or an older version is present).')
[void]$sb.AppendLine('ClassMethod DeployRoutine() As %Status')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    set tXData=##class(%Dictionary.CompiledXData).%OpenId(..%ClassName(1)_"||RoutineMac")')
[void]$sb.AppendLine('    if ''$ISOBJECT(tXData) quit $$$ERROR($$$GeneralError,"XData RoutineMac missing")')
[void]$sb.AppendLine('    set tText="" do tXData.Data.Rewind()')
[void]$sb.AppendLine('    while ''tXData.Data.AtEnd { set tText=tText_tXData.Data.Read(32000) }')
[void]$sb.AppendLine('    set tSource=$ZCONVERT($SYSTEM.Encryption.Base64Decode($TRANSLATE($PIECE($PIECE(tText,">",2),"<",1),$CHAR(9,10,13,32))),"I","UTF8")')
[void]$sb.AppendLine('    set tSource=$TRANSLATE(tSource,$CHAR(13))')
[void]$sb.AppendLine('    set tRoutine=##class(%Routine).%New("core.TafnitHelperUtils.MAC")')
[void]$sb.AppendLine('    do tRoutine.Clear()')
[void]$sb.AppendLine('    for i=1:1:$LENGTH(tSource,$CHAR(10)) {')
[void]$sb.AppendLine('        set tLine=$PIECE(tSource,$CHAR(10),i)')
[void]$sb.AppendLine('        continue:(i=1)&&($EXTRACT(tLine,1,8)="ROUTINE ")')
[void]$sb.AppendLine('        continue:(i=$LENGTH(tSource,$CHAR(10)))&&(tLine="")')
[void]$sb.AppendLine('        do tRoutine.WriteLine(tLine)')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('    set tSC=tRoutine.Save() quit:$$$ISERR(tSC) tSC')
[void]$sb.AppendLine('    quit tRoutine.Compile("-d")')
[void]$sb.AppendLine('}')
$files['RoutineMac'] = @{ Source = 'src\core.TafnitHelperUtils.mac'; Target = 'core.TafnitHelperUtils.MAC' }
foreach ($name in $files.Keys) {
    $f = $files[$name]
    $bytes = [IO.File]::ReadAllBytes((Join-Path $root $f.Source))
    $b64 = [Convert]::ToBase64String($bytes, [Base64FormattingOptions]::InsertLineBreaks)
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('/// ' + $f.Source + ' (' + $bytes.Length + ' bytes)')
    [void]$sb.AppendLine('XData ' + $name)
    [void]$sb.AppendLine('{')
    [void]$sb.AppendLine('<file target="' + $f.Target + '">')
    [void]$sb.AppendLine($b64)
    [void]$sb.AppendLine('</file>')
    [void]$sb.AppendLine('}')
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine('}')

$out = Join-Path $root 'src\TafnitCore.System.UI.App.Tools.Helper.WebFiles.cls'
[IO.File]::WriteAllText($out, ($sb.ToString() -replace "`r`n", "`n"), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Written $out"
